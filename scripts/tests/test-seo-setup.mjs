#!/usr/bin/env node
// test-seo-setup.mjs - The SEO a project receives (3.4.12): setup-seo.mjs on a fresh T3 project
// (the site's address read in one place, never localhost in production; robots.txt served by
// Next.js with its Sitemap line; a share image drawn by next/og; a sitemap without the fields
// Google ignores), run twice without a change; on a project an earlier version set up (only its
// own lines brought up to date, a robots.txt the person changed kept); and setup-i18n.mjs's
// sitemap and metadata reading the same address. No network, no vault.
//
//   node scripts/tests/test-seo-setup.mjs

import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SETUP = join(ROOT, "scripts", "setup-seo.mjs");

let checks = 0;
let failures = 0;
function check(label, ok, detail = "") {
  checks += 1;
  if (!ok) failures += 1;
  console.log(`${ok ? "OK  " : "FAIL"} ${label}${ok || !detail ? "" : `   (${String(detail).slice(0, 400)})`}`);
}

const LAYOUT = `import "~/styles/globals.css";

import { type Metadata } from "next";
import { Geist } from "next/font/google";

import { TRPCReactProvider } from "~/trpc/react";

export const metadata: Metadata = {
  title: "Create T3 App",
  description: "Generated by create-t3-app",
  icons: [{ rel: "icon", url: "/favicon.ico" }],
};

const geist = Geist({
  subsets: ["latin"],
  variable: "--font-geist-sans",
});

export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html lang="en" className={\`\${geist.variable}\`}>
      <body>
        <TRPCReactProvider>{children}</TRPCReactProvider>
      </body>
    </html>
  );
}
`;
// What the published 3.4.11 wrote, to the letter: the starting point of an update.
const OLD_METADATA_BASE = 'metadataBase: new URL(process.env.NEXT_PUBLIC_APP_URL ?? "http://localhost:3000"),';
const OLD_ROBOTS = "User-agent: *\nAllow: /\nDisallow: /api/\n";
const OLD_SITEMAP = `import type { MetadataRoute } from "next";

export default function sitemap(): MetadataRoute.Sitemap {
  const baseUrl = process.env.NEXT_PUBLIC_APP_URL ?? "http://localhost:3000";

  // Add every public page here as it's created. Exclude noindex pages (e.g. admin, preferences).
  const pages = [
    { path: "", changeFrequency: "weekly" as const, priority: 1.0 },
  ];

  return pages.map((page) => ({
    url: \`\${baseUrl}\${page.path}\`,
    lastModified: new Date(),
    changeFrequency: page.changeFrequency,
    priority: page.priority,
  }));
}
`;
const ARGS = ["--name", "L'Atelier de Jo", "--description", "Des cours de céramique à Lyon.", "--locale", "fr_FR"];
const project = () => {
  const dir = mkdtempSync(join(tmpdir(), "hv-seo-"));
  mkdirSync(join(dir, "src", "app"), { recursive: true });
  writeFileSync(join(dir, "src", "app", "layout.tsx"), LAYOUT);
  return dir;
};
const run = (dir) => spawnSync(process.execPath, [SETUP, ...ARGS], { cwd: dir, encoding: "utf8" });
const read = (dir, rel) => (existsSync(join(dir, rel)) ? readFileSync(join(dir, rel), "utf8") : null);
const snapshot = (dir) => {
  const out = {};
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else out[relative(dir, p).split("\\").join("/")] = readFileSync(p, "utf8");
    }
  };
  walk(dir);
  return out;
};
const dirs = [];

try {
  console.log("── Un projet neuf ──");
  {
    const dir = project();
    dirs.push(dir);
    const r = run(dir);
    check("setup-seo.mjs runs", r.status === 0, r.stderr);
    const files = snapshot(dir);
    const site = files["src/lib/site-url.ts"] ?? "";
    check("the site's address in one file: NEXT_PUBLIC_APP_URL, else Vercel's production domain, localhost last", site.includes("process.env.NEXT_PUBLIC_APP_URL") && site.includes("process.env.VERCEL_PROJECT_PRODUCTION_URL") && site.indexOf("VERCEL_PROJECT_PRODUCTION_URL") < site.indexOf('"http://localhost:3000"'));
    check("... a NEXT_PUBLIC_APP_URL that names this machine is not taken in production", /VERCEL_ENV === "production" && isLocal\(own\)/.test(site));
    const elsewhere = Object.entries(files).filter(([f, t]) => f !== "src/lib/site-url.ts" && /localhost/.test(t)).map(([f]) => f);
    check("no other file writes localhost", elsewhere.length === 0, elsewhere.join(", "));
    const layout = files["src/app/layout.tsx"];
    check("metadataBase and the JSON-LD read the site's address, imported once", layout.includes("metadataBase: new URL(siteUrl()),") && layout.includes("url: siteUrl(),") && layout.split('import { siteUrl } from "~/lib/site-url";').length === 2);
    check("no reference to a share picture that does not exist", !layout.includes("og-image.png"));
    const robots = files["src/app/robots.ts"] ?? "";
    check("robots.txt served by Next.js (src/app/robots.ts), with the sitemap's address", robots.includes("export default function robots(): MetadataRoute.Robots") && robots.includes("sitemap: `${siteUrl()}/sitemap.xml`") && !existsSync(join(dir, "public", "robots.txt")));
    check("... /api/ closed to robots, the share images under /api/og open", robots.includes('allow: ["/", "/api/og"], disallow: ["/api/"]'));
    const sitemap = files["src/app/sitemap.ts"] ?? "";
    check("the sitemap: no priority nor changeFrequency, no build date given as each page's", sitemap.includes("const baseUrl = siteUrl();") && !/changeFrequency:|priority:|new Date\(\)/.test(sitemap.replace(/^\s*\/\/.*$/gm, "")));
    const og = files["src/app/opengraph-image.tsx"] ?? "";
    check("a share image drawn by next/og from the name and description, 1200 by 630", og.includes('import { ImageResponse } from "next/og";') && og.includes("size = { width: 1200, height: 630 }") && og.includes('{"L\'Atelier de Jo"}') && og.includes('{"Des cours de céramique à Lyon."}'));
    check("... the texts as string expressions, never raw JSX text (an apostrophe there breaks the build)", !/>L'Atelier/.test(og));
    const again = run(dir);
    check("run again: nothing changes", again.status === 0 && JSON.stringify(snapshot(dir)) === JSON.stringify(files));
  }

  console.log("\n── Un projet mis en place par une version précédente ──");
  {
    const dir = project();
    dirs.push(dir);
    const layout = LAYOUT.replace(
      /export const metadata: Metadata = \{[\s\S]*?\};/,
      `export const metadata: Metadata = {\n  ${OLD_METADATA_BASE}\n  title: { default: "Jo", template: "%s | Jo" },\n  openGraph: {\n    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Jo" }],\n  },\n};`,
    ).replace("<TRPCReactProvider>{children}</TRPCReactProvider>", '<TRPCReactProvider>\n          <script dangerouslySetInnerHTML={{ __html: JSON.stringify({ "@context": "https://schema.org", "@type": "WebSite", name: "Jo",\n            url: process.env.NEXT_PUBLIC_APP_URL ?? "http://localhost:3000",\n          }) }} />\n          {children}\n        </TRPCReactProvider>');
    writeFileSync(join(dir, "src", "app", "layout.tsx"), layout);
    mkdirSync(join(dir, "public"), { recursive: true });
    writeFileSync(join(dir, "public", "robots.txt"), OLD_ROBOTS);
    writeFileSync(join(dir, "src", "app", "sitemap.ts"), OLD_SITEMAP);
    const r = run(dir);
    const after = read(dir, "src/app/layout.tsx");
    check("metadataBase and the JSON-LD brought to the site's address, the rest of the layout untouched", r.status === 0 && after.includes("metadataBase: new URL(siteUrl()),") && after.includes("url: siteUrl(),") && after.includes('title: { default: "Jo", template: "%s | Jo" },'));
    check("the reference to a share picture never made removed", !after.includes("og-image.png") && existsSync(join(dir, "src", "app", "opengraph-image.tsx")));
    check("the static robots.txt as it wrote it replaced by robots.ts (Next.js refuses both)", !existsSync(join(dir, "public", "robots.txt")) && existsSync(join(dir, "src", "app", "robots.ts")));
    check("the sitemap as it wrote it brought up to date", read(dir, "src/app/sitemap.ts").includes("const baseUrl = siteUrl();"));
  }
  {
    const dir = project();
    dirs.push(dir);
    writeFileSync(join(dir, "src", "app", "layout.tsx"), LAYOUT.replace(/export const metadata: Metadata = \{[\s\S]*?\};/, `export const metadata: Metadata = {\n  ${OLD_METADATA_BASE}\n  openGraph: {\n    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Jo" }],\n  },\n};`));
    mkdirSync(join(dir, "public"), { recursive: true });
    writeFileSync(join(dir, "public", "og-image.png"), "png");
    run(dir);
    check("an earlier layout whose share picture exists: its reference kept, no image drawn over it", read(dir, "src/app/layout.tsx").includes('images: [{ url: "/og-image.png"') && !existsSync(join(dir, "src", "app", "opengraph-image.tsx")));
  }
  {
    const dir = project();
    dirs.push(dir);
    mkdirSync(join(dir, "public"), { recursive: true });
    writeFileSync(join(dir, "public", "robots.txt"), "User-agent: *\nDisallow: /prive/\n");
    writeFileSync(join(dir, "public", "og-image.png"), "png");
    writeFileSync(join(dir, "src", "app", "sitemap.ts"), "export default function sitemap() { return []; }\n");
    const r = run(dir);
    check("a robots.txt the person changed: kept, robots.ts not created, said", r.status === 0 && read(dir, "public/robots.txt") === "User-agent: *\nDisallow: /prive/\n" && !existsSync(join(dir, "src", "app", "robots.ts")) && /changed by the project, kept/.test(r.stdout));
    check("a share picture of its own: no image drawn over it", !existsSync(join(dir, "src", "app", "opengraph-image.tsx")));
    check("a sitemap the person wrote: left as it is", read(dir, "src/app/sitemap.ts") === "export default function sitemap() { return []; }\n");
  }

  console.log("\n── Les langues (setup-i18n.mjs) ──");
  {
    const i18n = readFileSync(join(ROOT, "scripts", "setup-i18n.mjs"), "utf8");
    check("setup-i18n.mjs makes sure the site's address file exists", i18n.includes('import { ensureSiteUrl } from "./_site-url.mjs";') && i18n.includes("ensureSiteUrl(webDir)"));
    check("... its canonical and hreflang helper and its layout read it, never localhost", !i18n.includes('process.env.NEXT_PUBLIC_APP_URL ?? "http://localhost:3000"') && i18n.split("siteUrl()").length >= 3);
    const block = i18n.slice(i18n.indexOf("const newBlock"), i18n.indexOf("if (simpleMapRe.test(sm))")).replace(/^\s*\/\/.*$/gm, "");
    check("... its per-language sitemap writes no ignored field nor the build's date", block.length > 0 && !/changeFrequency|priority|new Date\(\)/.test(block) && block.includes('"lastModified" in page'));
  }

} finally {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
}

console.log(`\n${checks - failures}/${checks} checks`);
process.exitCode = failures ? 1 : 0;
